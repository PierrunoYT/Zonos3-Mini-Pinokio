module.exports = {
  version: "7.0",
  title: "ZONOS3-Mini",
  description: "Zyphra's compact multilingual text-to-speech (43 languages) with voice cloning, voice design and emotion steering. Runs the native ggml server with Zonos Voice Studio (CUDA, Metal or CPU). https://huggingface.co/Zyphra/ZONOS3-Mini",
  icon: "icon.png",
  menu: async (kernel, info) => {
    let installed = info.exists("app/servers/ggml/build/" + (kernel.platform === "win32" ? "zonos3-server.exe" : "zonos3-server"))
    let running = {
      install: info.running("install.js"),
      start: info.running("start.js"),
      update: info.running("update.js"),
      reset: info.running("reset.js"),
      extras: info.running("extras.js")
    }
    if (running.install) {
      return [{
        default: true,
        icon: "fa-solid fa-plug",
        text: "Installing",
        href: "install.js",
      }]
    } else if (installed) {
      if (running.start) {
        let local = info.local("start.js")
        if (local && local.url) {
          return [{
            default: true,
            icon: "fa-solid fa-rocket",
            text: "Open Web UI",
            href: local.url,
          }, {
            icon: "fa-solid fa-terminal",
            text: "Terminal",
            href: "start.js",
          }]
        } else {
          return [{
            default: true,
            icon: "fa-solid fa-terminal",
            text: "Terminal",
            href: "start.js",
          }]
        }
      } else if (running.update) {
        return [{
          default: true,
          icon: "fa-solid fa-terminal",
          text: "Updating",
          href: "update.js",
        }]
      } else if (running.reset) {
        return [{
          default: true,
          icon: "fa-solid fa-terminal",
          text: "Resetting",
          href: "reset.js",
        }]
      } else if (running.extras) {
        return [{
          default: true,
          icon: "fa-solid fa-download",
          text: "Downloading",
          href: "extras.js",
        }]
      } else {
        return [{
          default: true,
          icon: "fa-solid fa-power-off",
          text: "Start",
          href: "start.js",
        }, {
          icon: "fa-solid fa-download",
          text: "<div><strong>Download Extra Models</strong><div>Raw-reference cloning + full-size decoder (~7.8 GB)</div></div>",
          href: "extras.js",
        }, {
          icon: "fa-solid fa-plug",
          text: "Update",
          href: "update.js",
        }, {
          icon: "fa-solid fa-plug",
          text: "Install",
          href: "install.js",
        }, {
          icon: "fa-regular fa-circle-xmark",
          text: "<div><strong>Reset</strong><div>Revert to pre-install state (keeps downloaded weights)</div></div>",
          href: "reset.js",
          confirm: "Are you sure you wish to reset the app?"
        }]
      }
    } else {
      return [{
        default: true,
        icon: "fa-solid fa-plug",
        text: "Install",
        href: "install.js",
      }]
    }
  }
}
